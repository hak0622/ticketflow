ROOT = Path(__file__).resolve().parents[1]
COMPOSE = ROOT / 'perf/compose.yml'


def command(args, *, cwd=ROOT, env=None, data=None, logfile=None, check=True):
    if logfile:
        with open(logfile, 'w') as log:
            p = subprocess.run(args, cwd=cwd, env=env, input=data, text=True, stdout=log, stderr=subprocess.STDOUT)
        output = ''
    else:
        p = subprocess.run(args, cwd=cwd, env=env, input=data, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        output = p.stdout
    if check and p.returncode:
        raise RuntimeError(f'{args[:5]} exited {p.returncode}; see {logfile or p.stderr[-2000:]}')
    return output, p.returncode


def http(url, method='GET'):
    req = urllib.request.Request(url, method=method)
    with urllib.request.urlopen(req, timeout=15) as response:
        return response.read().decode()


class Environment:
    def __init__(self, project, jar, results, sold_out_state="REJECTED", users=500):
        if not project.startswith('tfperf-'):
            raise ValueError('Refusing an unrelated Docker project')
        self.sold_out_state = sold_out_state
        self.users = users
        self.k6_base_url = 'http://app:8080'
        self.project = project
        self.results = results
        self.env = dict(os.environ, PERF_APP_JAR=str(jar), PERF_RESULTS=str(results))
        self.base = ['docker', 'compose', '-f', str(COMPOSE), '-p', project]
        self.url = None
        self.metrics_url = None

    def dc(self, *args, **kwargs):
        return command(self.base + list(args), env=self.env, **kwargs)

    def sql(self, query):
        return self.dc('exec', '-T', 'mysql', 'mysql', '-uroot', '-pperf-only-password',
                       '-N', '-B', 'ticketflow_perf', data=query)[0].strip()

    def redis(self, *args):
        return self.dc('exec', '-T', 'redis', 'redis-cli', '--raw', *map(str, args))[0].strip()

    def start(self):
        self.dc('up', '-d', '--wait', 'mysql', 'redis', logfile=self.results / 'infra-start.log')
        # Fixture users are preseeded before startup. Password login is unused; fresh JWTs
        # are issued by the EXISTING test-support CSV endpoint, not hand-signed here.
        user_sql = """CREATE TABLE users (
            id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
            email VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255),
            nickname VARCHAR(255) UNIQUE, role ENUM('USER','ADMIN') NOT NULL);
        INSERT INTO users(email,password,role) VALUES """
        user_sql += ','.join(f"('test{i}@test.com','unused-perf-fixture','USER')" for i in range(1, 501)) + ';'
        self.sql(user_sql)
        self.dc('up', '-d', 'app', logfile=self.results / 'app-start.log')
        port = self.dc('port', 'app', '8080')[0].strip().rsplit(':', 1)[1]
        self.url = 'http://127.0.0.1:' + port
        metrics_port = self.dc('port', 'app', '8081')[0].strip().rsplit(':', 1)[1]
        self.metrics_url = 'http://127.0.0.1:' + metrics_port
        deadline = time.monotonic() + 180
        while time.monotonic() < deadline:
            try:
                if json.loads(http(self.metrics_url + '/actuator/health')).get('status') == 'UP':
                    # Startup runners finish before all 500 fresh JWTs are available.
                    content = http(self.url + '/api/test-support/csv')
                    rows = list(csv.DictReader(io.StringIO(content)))
                    if len(rows) == 500 and len({r['userId'] for r in rows}) == 500:
                        for row in rows:
                            payload = json.loads(base64.urlsafe_b64decode(row['token'].split('.')[1] + '==='))
                            assert payload['id'] == int(row['userId'])
                        (self.results / 'users.csv').write_text(content)
                        return
            except Exception:
                pass
            time.sleep(1)
        raise RuntimeError('Disposable app did not become ready; inspect app.log')

    def concert(self, title, capacity, mode):
        # Title is generated by this runner, never accepted as arbitrary SQL input.
        assert re.fullmatch(r'[a-zA-Z0-9_-]+', title)
        result = self.sql(f"""INSERT INTO concert(title,event_at,total_seats,booked_count,status,version,price)
            VALUES('{title}',DATE_ADD(NOW(),INTERVAL 7 DAY),{int(capacity)},0,'OPEN',0,90000);
            SELECT LAST_INSERT_ID();""")
        concert_id = int(result)
        setup_mode = 'BOOKING' if mode == 'api' else 'QUEUE'
        response = json.loads(http(f'{self.url}/api/test-support/concerts/{concert_id}/setup?mode={setup_mode}&ttlSeconds=600', 'POST'))
        if mode == 'api':
            assert int(self.redis('GET', f'seats:concert:{concert_id}')) == capacity
            assert self.redis('EXISTS', f'admitted:concert:{concert_id}:user:1') == '1'
        return concert_id

    def has_attempts(self):
        return self.sql("SELECT COUNT(*) FROM information_schema.tables WHERE table_schema=DATABASE() AND table_name='booking_attempt'") == '1'

    def settle_and_verify(self, cid, capacity, modern, successful_http):
        deadline = time.monotonic() + 120
        stable = 0
        states = {}
        while time.monotonic() < deadline:
            if modern:
                rows = self.sql(f"SELECT status,COUNT(*) FROM booking_attempt WHERE concert_id={cid} GROUP BY status")
                states = {r.split('\t')[0]: int(r.split('\t')[1]) for r in rows.splitlines() if r}
                if sum(states.values()) == self.users and not (states.get('REQUESTED', 0) + states.get('RELEASE_PENDING', 0)):
                    stable += 1
                else:
                    stable = 0
            else:
                # No durable attempts existed before this refactor. k6 finished all HTTP calls;
                # wait a worker interval, then take the final Redis/Booking snapshot below.
                stable += 1
            if stable >= 2:
                break
            time.sleep(5)
        sqlrow = self.sql(f"""SELECT COUNT(*),COUNT(DISTINCT user_id),
            COALESCE(SUM(status IN ('PENDING_PAYMENT','CONFIRMED')),0),COALESCE(SUM(status='CANCELLED'),0)
            FROM booking WHERE concert_id={cid};""")
        total, unique, active, cancelled = map(int, sqlrow.split('\t'))
        remaining_raw = self.redis('GET', f'seats:concert:{cid}')
        remaining = int(remaining_raw) if remaining_raw else None
        checks = {
            'no_oversell': 0 <= active <= capacity,
            'no_duplicate_booking': total == unique,
            'quantity_conserved': remaining is not None and remaining >= 0 and remaining + active == capacity,
            'expected_success_count': active == min(self.users, capacity),
            'http_success_matches_db': active == successful_http,
        }
        details = {'remaining': remaining, 'booking_rows': total, 'unique_booking_users': unique,
                   'active_bookings': active, 'cancelled_bookings': cancelled, 'attempt_states': states if modern else None}
        if modern:
            anomalies = int(self.sql(f"""SELECT COUNT(*) FROM booking_attempt a LEFT JOIN booking b ON b.id=a.booking_id
                WHERE a.concert_id={cid} AND (
                  (a.status='BOOKED' AND (b.id IS NULL OR b.concert_id<>a.concert_id OR b.user_id<>a.user_id OR b.status='CANCELLED'))
                  OR (a.status='RELEASED' AND a.booking_id IS NOT NULL AND (b.id IS NULL OR b.status<>'CANCELLED'))
                  OR (a.status='REJECTED' AND (a.booking_id IS NOT NULL OR a.result_status<>'SOLD_OUT')));"""))
            attempt_rows = self.sql(f'SELECT id,user_id,status,result_status FROM booking_attempt WHERE concert_id={cid}')
            # One Redis EVAL is used for read-only validation after measurements, avoiding
            # 1,000 docker exec calls and never rebuilding/overwriting stock from DB counts.
            args = []
            for row in attempt_rows.splitlines():
                aid, uid, state, result = row.split('\t'); args += [aid, uid, state, result]
            lua = """local bad=0; for i=1,#ARGV,4 do
              local id=ARGV[i]; local uid=ARGV[i+1]; local s=ARGV[i+2];
              local key='booking:attempt:'..id;
              if redis.call('HGET',key,'owner')~=KEYS[1]..':'..uid then bad=bad+1 end;
              local marker=redis.call('HGET','booking:attempt:'..id,'state');
              if s=='BOOKED' then
                if marker~='HELD' or redis.call('GET','booking:active:concert:'..KEYS[1]..':user:'..uid)~=id then bad=bad+1 end;
              elseif s=='RELEASED' then
                if marker~='RELEASED' then bad=bad+1 end;
              elseif s=='REJECTED' then
                if ARGV[i+3]~='SOLD_OUT' or marker~='RELEASED' or redis.call('HGET',key,'result')~='SOLD_OUT'
                  or redis.call('HEXISTS',key,'remaining')==1 or redis.call('HEXISTS',key,'admissionExpires')==1
                  or redis.call('EXISTS','booking:active:concert:'..KEYS[1]..':user:'..uid)==1 then bad=bad+1 end;
              else bad=bad+1 end;
            end; return bad"""
            marker_anomalies = int(self.redis('EVAL', lua, 1, cid, *args)) if args else -1
            checks.update({f'all_{self.users}_attempts_recorded': sum(states.values()) == self.users,
                           'no_unfinished_attempts': not (states.get('REQUESTED', 0) + states.get('RELEASE_PENDING', 0)),
                           'exact_terminal_counts': states.get('BOOKED', 0) == min(self.users, capacity)
                               and states.get(self.sold_out_state, 0) == max(0, self.users-capacity)
                               and sum(states.values()) == min(self.users, capacity) + states.get(self.sold_out_state, 0),
                           'valid_attempt_booking_links': anomalies == 0,
                           'redis_markers_match_attempts': marker_anomalies == 0})
            details.update(attempt_link_anomalies=anomalies, marker_anomalies=marker_anomalies)
        return dict(checks=checks, passed=all(checks.values()), **details)

    def close(self):
        try:
            self.dc('logs', '--no-color', 'app', logfile=self.results / 'app.log', check=False)
            self.dc('ps', '-a', '--format', 'json', logfile=self.results / 'containers.json', check=False)
        finally:
            self.dc('down', '-v', '--remove-orphans', logfile=self.results / 'cleanup.log', check=False)


class PoolMonitor:
    def __init__(self, url, output):
        self.url = url; self.output = output; self.stop = threading.Event(); self.samples = []
        self.thread = threading.Thread(target=self.run, daemon=True)

    def run(self):
        with self.output.open('w') as file:
            while not self.stop.is_set():
                sample = {'time_ms': time.time()*1000}
                try:
                    text = http(self.url + '/actuator/prometheus')
                    for name in ['hikaricp_connections_active','hikaricp_connections_idle','hikaricp_connections_pending',
                                 'hikaricp_connections_max','hikaricp_connections_timeout_total',
                                 'hikaricp_connections_acquire_seconds_count','hikaricp_connections_acquire_seconds_sum']:
                        vals = re.findall(r'^'+re.escape(name)+r'(?:\{[^\n]*\})? ([0-9.eE+-]+)$', text, re.M)
                        sample[name] = sum(map(float, vals)) if vals else None
                except Exception as error:
                    sample['error'] = str(error)
                self.samples.append(sample); file.write(json.dumps(sample)+'\n'); file.flush()
                self.stop.wait(.1)

    def finish(self, start, end):
        self.stop.set(); self.thread.join(20)
        samples = [s for s in self.samples if start <= s['time_ms'] <= end]
        active = [s['hikaricp_connections_active'] for s in samples if s.get('hikaricp_connections_active') is not None]
        pending = [s['hikaricp_connections_pending'] for s in samples if s.get('hikaricp_connections_pending') is not None]
        maximum = [s['hikaricp_connections_max'] for s in samples if s.get('hikaricp_connections_max') is not None]
        timeout_values = [s['hikaricp_connections_timeout_total'] for s in self.samples
                          if s.get('hikaricp_connections_timeout_total') is not None]
        timeout_delta = timeout_values[-1] - timeout_values[0] if len(timeout_values) >= 2 else None
        return {'observed_acquire_timeout_delta': timeout_delta, 'sample_count': len(samples), 'observed_active_peak': max(active) if active else None,
                'observed_active_avg': statistics.mean(active) if active else None,
                'observed_pending_peak': max(pending) if pending else None,
                'configured_max_observed': max(maximum) if maximum else None,
                'nominal_interval_ms': 100}


def metric(summary, name, field, default=0):
    return summary.get('metrics', {}).get(name, {}).get('values', {}).get(field, default)


def measure(environment, label, capacity, mode, modern, warmup=False):
    cid = environment.concert(label, capacity, mode)
    monitor = PoolMonitor(environment.metrics_url, environment.results / (label+'-pool.ndjson'))
    monitor.thread.start()
    try:
        _, code = environment.dc('run', '--rm', '--no-deps', '-T', 'k6', 'run',
            '-e', f'BASE_URL={environment.k6_base_url}', '-e', f'USERS={environment.users}', '-e', f'MODE={mode}',
            '-e', f'CAPACITY={capacity}', '-e', f'WARMUP={str(warmup).lower()}', '-e', f'CONCERT_ID={cid}', '-e', f'RUN_ID={uuid.uuid4()}',
            '-e', f'OUTPUT={label}', '/scripts/booking.js', logfile=environment.results/(label+'-k6.log'), check=False)
        summary = json.loads((environment.results/(label+'.json')).read_text())
        start = metric(summary, 'user_started_at_ms', 'min')
        end = metric(summary, 'user_finished_at_ms', 'max')
    finally:
        if 'start' not in locals():
            start, end = 0, time.time()*1000
        pool = monitor.finish(start, end)
    booked = int(metric(summary, 'booked', 'count'))
    verification = environment.settle_and_verify(cid, capacity, modern, booked)
    span = (end-start)/1000
    row = {'label': label, 'mode': mode, 'capacity': capacity, 'users': environment.users, 'concert_id': cid,
           'k6_exit_code': code, 'booking_avg_ms': metric(summary,'booking_duration','avg',None),
           'booking_p95_ms': metric(summary,'booking_duration','p(95)',None),
           'flow_avg_ms': metric(summary,'flow_duration','avg',None),
           'flow_p95_ms': metric(summary,'flow_duration','p(95)',None),
           'burst_seconds': span, 'booking_posts': int(metric(summary,'booking_attempts','count')),
           'completed_users': int(metric(summary,'completed_users','count')),
           'booked': booked, 'sold_out': int(metric(summary,'sold_out','count')),
           'already_booked': int(metric(summary,'already_booked','count')),
           'processing': int(metric(summary,'processing','count')),
           'unexpected_error_rate': metric(summary,'unexpected_errors','rate',None),
           'http_failure_rate': metric(summary,'http_req_failed','rate',None),
           'completed_users_per_second': metric(summary,'completed_users','count')/span if span else None,
           'successful_bookings_per_second': booked/span if span else None,
           'http_requests': int(metric(summary,'http_reqs','count')),
           'pool': pool, 'verification': verification, 'warmup': warmup}
    row['passed'] = code == 0 and verification['passed'] and row['booking_posts'] == environment.users and pool['sample_count'] > 0 and pool['observed_active_peak'] is not None
    (environment.results/(label+'-verified.json')).write_text(json.dumps(row,indent=2))
    print(json.dumps({k:row[k] for k in ['label','passed','booking_avg_ms','booking_p95_ms','booked','sold_out'] }),flush=True)
    return row


def build_jar(directory, log):
    command(['./gradlew','bootJar','-x','test','--offline'], cwd=directory, logfile=log)
    jars = list((directory/'build/libs').glob('*.jar'))
    if len(jars) != 1:
        raise RuntimeError(f'Expected one bootJar, found {jars}')
    return jars[0]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--baseline-ref', default='HEAD')
    parser.add_argument('--repeats',type=int,default=3)
    parser.add_argument('--current-only',action='store_true')
    parser.add_argument('--historical-results', type=Path, help='Reuse the baseline/current JARs preserved by a previous run')
    args=parser.parse_args()
    if args.current_only and args.historical_results:
        parser.error('--current-only and --historical-results are mutually exclusive')
    if args.repeats < 1:
        raise ValueError('repeats must be positive')
    runid = time.strftime('%Y%m%d-%H%M%S')+'-'+uuid.uuid4().hex[:6]
    results=ROOT/'build/performance'/runid; results.mkdir(parents=True)
    print('Results:', results, flush=True)
    docker_info=json.loads(command(['docker','info','--format','{{json .}}'])[0])
    baseline=command(['git','rev-parse',args.baseline_ref])[0].strip()
    metadata={'run_id':runid,'baseline_commit':baseline, 'current_head':command(['git','rev-parse','HEAD'])[0].strip(),
              'current_dirty_diff': 'current-working-tree.patch','repeats':args.repeats,
              'docker_cpus':docker_info.get('NCPU'),'docker_memory_bytes':docker_info.get('MemTotal'),
              'docker_version':docker_info.get('ServerVersion'), 'started_at':time.strftime('%Y-%m-%dT%H:%M:%S%z')}
    (results/'current-working-tree.patch').write_text(command(['git','diff','HEAD'])[0])
    # Untracked stage-1/2 sources are part of current; record hashes without capturing credentials.
    source_files=list((ROOT/'src/main').rglob('*'))
    import hashlib
    metadata['current_source_sha256']={str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in source_files if p.is_file()}
    (results/'environment.json').write_text(json.dumps(metadata,indent=2))
    image_output = command(['docker','image','inspect', 'mysql:8.4','redis:7-alpine',
        'eclipse-temurin:17-jre-jammy','grafana/k6:1.0.0','--format','{{json .RepoDigests}}'])[0]
    metadata['image_digests'] = [json.loads(line) for line in image_output.splitlines()]
    variants=[]
    with tempfile.TemporaryDirectory(prefix='ticketflow-perf-baseline-') as temp:
        if args.historical_results:
            previous = args.historical_results.resolve()
            old = json.loads((previous/'environment.json').read_text())
            metadata['historical_results'] = str(previous)
            metadata['baseline_commit'] = old['baseline_commit']
            for name, original in [('baseline','baseline'),('recovery','current')]:
                jar = previous/original/'app.jar'
                if hashlib.sha256(jar.read_bytes()).hexdigest() != old['jar_sha256'][original]:
                    raise RuntimeError('Historical JAR hash mismatch: ' + str(jar))
                variants.append((name, jar))
        elif not args.current_only:
            snapshot=Path(temp)
            payload=subprocess.check_output(['git','archive',baseline],cwd=ROOT)
            with tarfile.open(fileobj=io.BytesIO(payload)) as archive:
                archive.extractall(snapshot)
            print('Building baseline',baseline,flush=True)
            variants.append(('baseline',build_jar(snapshot,results/'baseline-build.log')))
        print('Building current working tree',flush=True)
        variants.append(('current',build_jar(ROOT,results/'current-build.log')))
        all_rows=[]
        for name,jar in variants:
            folder=results/name;folder.mkdir()
            saved_jar=folder/'app.jar';shutil.copy2(jar,saved_jar)
            metadata.setdefault('jar_sha256',{})[name]=hashlib.sha256(saved_jar.read_bytes()).hexdigest()
            environment=Environment('tfperf-'+runid.lower()+'-'+name,saved_jar,folder,
                                    sold_out_state='RELEASED' if name=='recovery' else 'REJECTED')
            print('Starting isolated',name,'environment',flush=True)
            try:
                environment.start()
                modern=environment.has_attempts()
                if name=='current' and not modern:
                    raise RuntimeError('Current artifact has no booking_attempt schema')
                metadata.setdefault('runtime',{})[name]={'has_attempts':modern,'url':environment.url,'metrics_url':environment.metrics_url}
                if not measure(environment,'warmup',500,'api',modern,warmup=True)['passed']:
                    raise RuntimeError('Warmup correctness/telemetry check failed')
                for repeat in range(1,args.repeats+1):
                    for mode,capacity in [('api',500),('api',300),('flow',500)]:
                        label=f'{name}-{mode}-{capacity}-r{repeat}'
                        all_rows.append(dict(variant=name,repeat=repeat,**measure(environment,label,capacity,mode,modern)))
                        (results/'runs.json').write_text(json.dumps(all_rows,indent=2))
            finally:
                environment.close()
                (results/'environment.json').write_text(json.dumps(metadata,indent=2))
        comparison=[]
        for name,_ in variants:
            for mode,capacity in [('api',500),('api',300),('flow',500)]:
                selected=[r for r in all_rows if r['variant']==name and r['mode']==mode and r['capacity']==capacity]
                row={'variant':name,'mode':mode,'capacity':capacity,'runs':len(selected),'all_passed':all(r['passed'] for r in selected)}
                for field in ['booking_avg_ms','booking_p95_ms','flow_avg_ms','flow_p95_ms','completed_users_per_second',
                              'successful_bookings_per_second','unexpected_error_rate']:
                    values=[r[field] for r in selected if r[field] is not None]
                    row[field+'_median']=statistics.median(values) if values else None
                    row[field+'_range']=[min(values),max(values)] if values else None
                row['unexpected_error_count']=sum(round(r['unexpected_error_rate']*r['completed_users']) for r in selected)
                row['unexpected_error_rate_pooled']=row['unexpected_error_count']/sum(r['completed_users'] for r in selected)
                row['pool_active_peak_observed']=max((r['pool']['observed_active_peak'] for r in selected if r['pool']['observed_active_peak'] is not None), default=None)
                row['pool_pending_peak_observed']=max((r['pool']['observed_pending_peak'] for r in selected if r['pool']['observed_pending_peak'] is not None), default=None)
                comparison.append(row)
        (results/'comparison.json').write_text(json.dumps(comparison,indent=2))
        print('Finished:',results,'all_passed=',all(r['passed'] for r in all_rows),flush=True)
        if not all(r['passed'] for r in all_rows):
            raise SystemExit(1)

if __name__=='__main__':
    main()
